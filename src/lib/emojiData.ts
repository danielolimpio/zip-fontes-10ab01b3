export const getAllEmojis = (): string[] => {
  return emojiCategories.flatMap(cat => cat.emojis);
};

export const searchEmojis = (query: string): string[] => {
  if (!query.trim()) return getAllEmojis();
  
  const lowerQuery = query.toLowerCase();
  
  // Search in category names and return all emojis from matching categories
  const matchingCategories = emojiCategories.filter(cat => 
    cat.name.toLowerCase().includes(lowerQuery)
  );
  
  if (matchingCategories.length > 0) {
    return matchingCategories.flatMap(cat => cat.emojis);
  }
  
  return getAllEmojis();
};
